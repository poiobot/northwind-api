"""
VectorIndexer — orchestrates embedding and retrieval for Spore entities.

Reads the project's VectorConfig JSON (generated by VectorKeyAnalyzer during
code generation) to know which fields to embed for each collection. Delegates
to any VectorServiceInterface implementation for the actual embedding + storage.

Usage (from hooks or batch scripts):

    from data.vector_indexer import VectorIndexer
    from services.vector.impl.ollama_vector import OllamaVectorService
    from api import settings

    _service = OllamaVectorService(
        base_url=settings.EMBEDDING_BASE_URL,
        model=settings.EMBEDDING_MODEL,
    )
    indexer = VectorIndexer(vector_service=_service)
    indexer.index_record(collection="bridges", record={"_id": "...", "name": "...", ...})
"""
import json
import logging
from pathlib import Path
from string import Formatter
from collections import defaultdict
from typing import Any, Dict, List, Optional

from services.vector.vector_service_interface import VectorServiceInterface

logger = logging.getLogger(__name__)

# Default location relative to the project root (same directory as .env)
_DEFAULT_CONFIG_GLOB = "schema/*_vector_config.json"


def _safe_format(template: str, data: Dict[str, Any]) -> str:
    """Format template using data, substituting empty string for missing keys."""
    fallback = defaultdict(str, {k: ("" if v is None else str(v)) for k, v in data.items()})
    try:
        return template.format_map(fallback)
    except (KeyError, ValueError):
        # Strip unknown placeholders and return best-effort text
        field_names = [fn for _, fn, _, _ in Formatter().parse(template) if fn]
        return " ".join(str(data.get(f, "")) for f in field_names if data.get(f))


class VectorIndexer:
    """Reads VectorConfig and drives embedding + storage for entity records."""

    def __init__(
        self,
        vector_service: VectorServiceInterface,
        config_path: Optional[str] = None,
        vector_config: Optional[Dict] = None,
    ):
        """
        Args:
            vector_service: Concrete VectorServiceInterface (e.g. OllamaVectorService).
            config_path:    Path to the project's *_vector_config.json file.
                            If None, the indexer searches schema/ automatically.
            vector_config:  Pre-loaded VectorConfig dict (bypasses file loading).
        """
        self.service = vector_service
        self._config: Dict[str, Any] = vector_config or self._load_config(config_path)
        # Build reverse map: entity class name → collection name
        self._entity_to_collection: Dict[str, str] = {
            v["entity_name"]: k
            for k, v in self._config.items()
            if "entity_name" in v
        }

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def index_record(self, collection: str, record: Dict[str, Any]) -> bool:
        """Embed and upsert a single record dict for the given collection.

        Args:
            collection: Collection/table name (e.g. "bridges").
            record:     Document dict with at least '_id' (or 'id') key.

        Returns:
            True if the vector was successfully stored.
        """
        coll_config = self._config.get(collection)
        if not coll_config:
            logger.debug("No VectorConfig for collection '%s' — skipping.", collection)
            return False

        record_id = str(record.get("_id") or record.get("id") or "")
        if not record_id:
            logger.warning("Record in '%s' has no id — cannot index.", collection)
            return False

        aliases = self._extract_aliases(coll_config, record)
        text = self._build_text(coll_config, record, aliases)

        if not text.strip():
            logger.debug("Empty composite text for %s/%s — skipping.", collection, record_id)
            return False

        return self.service.upsert(
            id=record_id,
            collection=collection,
            aliases=aliases,
            text=text,
        )

    def index_from_entity(self, entity_name: str, entity: Any) -> bool:
        """Index a Pydantic model instance.

        Args:
            entity_name: PascalCase entity class name (e.g. "Bridge").
            entity:      A Pydantic BaseModel instance with model_dump().

        Returns:
            True on success.
        """
        collection = self._entity_to_collection.get(entity_name)
        if not collection:
            logger.debug("No VectorConfig for entity '%s' — skipping.", entity_name)
            return False

        try:
            record = entity.model_dump(by_alias=True)
        except AttributeError:
            record = dict(entity)

        return self.index_record(collection=collection, record=record)

    def remove_record(self, collection: str, record_id: str) -> bool:
        """Delete the vector for a record.

        Args:
            collection: Collection name.
            record_id:  Record primary identifier as string.

        Returns:
            True if found and deleted.
        """
        return self.service.delete(id=str(record_id), collection=collection)

    def search(
        self,
        query: str,
        collection: Optional[str] = None,
        limit: int = 10,
    ) -> List[Dict[str, Any]]:
        """Semantic search across indexed records.

        Args:
            query:      Natural-language query string.
            collection: Restrict search to this collection (optional).
            limit:      Maximum number of results.

        Returns:
            List of result dicts {id, collection, aliases, text, score}.
        """
        return self.service.search(query_text=query, collection=collection, limit=limit)

    def batch_index(self, collection: str, records: List[Dict[str, Any]]) -> int:
        """Index a list of records for a collection.

        Returns:
            Count of successfully indexed records.
        """
        count = 0
        for record in records:
            if self.index_record(collection=collection, record=record):
                count += 1
        return count

    def collection_for_entity(self, entity_name: str) -> Optional[str]:
        """Return the collection name for a given entity class name."""
        return self._entity_to_collection.get(entity_name)

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    def _extract_aliases(self, config: Dict, record: Dict) -> List[str]:
        aliases = []
        for field in config.get("alias_fields", []):
            value = record.get(field)
            if value:
                aliases.append(str(value))
        return aliases

    def _build_text(self, config: Dict, record: Dict, aliases: List[str]) -> str:
        template = config.get("composite_template", "")
        if template:
            return _safe_format(template, record)
        # Fallback: join aliases + semantic field values
        parts = list(aliases)
        for field in config.get("semantic_fields", []):
            value = record.get(field)
            if value:
                parts.append(str(value))
        return ". ".join(parts)

    @staticmethod
    def _load_config(config_path: Optional[str]) -> Dict:
        if config_path:
            path = Path(config_path)
            if path.exists():
                with open(path) as fh:
                    return json.load(fh)
            logger.warning("VectorConfig not found at %s", config_path)
            return {}

        # Auto-discover from schema/ directory
        matches = list(Path(".").glob(_DEFAULT_CONFIG_GLOB))
        if matches:
            with open(matches[0]) as fh:
                logger.info("Loaded VectorConfig from %s", matches[0])
                return json.load(fh)

        logger.info("No VectorConfig found — vector indexing disabled.")
        return {}
